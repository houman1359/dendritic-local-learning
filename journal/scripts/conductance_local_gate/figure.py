def sci_parts(value, digits=1):
    """['5.7', ' × 10', ('sup', '−4')] for 5.666e-4."""
    exponent = int(math.floor(math.log10(abs(value))))
    mantissa = value / 10.0 ** exponent
    text = f'{mantissa:.{digits}f}'
    if text in ('1.0', '1'):
        return ['10', ('sup', true_minus(exponent))]
    return [text, ' × 10', ('sup', true_minus(exponent))]


def plain_log_ticks(ax, ticks=LOG_TICKS, pad_pt=3.0):
    """Log ticks printed as ``10`` with a raised exponent, both at 7.0 pt.

    The tick label itself stays a real tick label (so ``NativeCanvas`` still
    measures the left reserve from the axis) and the exponent is annotated
    into the extra pad the tick label leaves.
    """
    ax.set_yscale('log')
    ax.yaxis.set_major_locator(FixedLocator(list(ticks)))
    ax.set_yticks(list(ticks))
    exps = [true_minus(int(round(math.log10(t)))) for t in ticks]
    widest = max(_text_w_pt(ax, e, PT_BASE) for e in exps)
    ax.set_yticklabels(['10'] * len(ticks))
    ax.tick_params(axis='y', pad=pad_pt + widest)
    ax.yaxis.set_minor_locator(NullLocator())
    ax.yaxis.set_minor_formatter(NullFormatter())
    # the exponent is anchored to the RIGHT EDGE of its own '10', not to the
    # spine: pinning it to the spine leaves a gap as wide as the difference
    # between this exponent and the widest one, which prints '10  0' instead
    # of a raised exponent.
    for label, exp in zip(ax.get_yticklabels(), exps):
        ax.annotate(exp, xy=(1.0, 0.42), xycoords=label, xytext=(0.4, 2.2),
                    textcoords='offset points', fontsize=PT_BASE,
                    color=COLORS['ink'], ha='left', va='center',
                    annotation_clip=False)
    return ax


def window_rule(ax, x=PRIMARY['budget'], *, top=REF_TOP, pad_pt=1.4):
    """The dotted window reference, drawn LAST and stepped around the text.

    ``reference_line`` draws one segment, so a full-height rule strikes
    through every direct label and note that spans its x (HEAD and v1 struck
    four lines in each of C and D).  The rule stops at ``top`` -- just above
    the highest trace -- and every text span it would cross is subtracted
    from it, so the reader still reads one dotted rule and no crossed type.
    """
    fig = ax.get_figure()
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    k = 72.0 / fig.dpi
    x_disp = ax.transData.transform((x, 1.0))[0]
    y_lo = ax.transData.transform((x, LOG_YLIM[0]))[1]
    y_hi = ax.transData.transform((x, top))[1]
    gaps = []
    for art in list(ax.texts) + [t for leg in ax.get_legend() and
                                 [ax.get_legend()] or [] for t in leg.get_texts()]:
        try:
            bb = art.get_window_extent(renderer)
        except Exception:
            continue
        if bb.x0 - pad_pt / k > x_disp or bb.x1 + pad_pt / k < x_disp:
            continue
        if bb.y1 < y_lo or bb.y0 > y_hi:
            continue
        gaps.append((bb.y0 - pad_pt / k, bb.y1 + pad_pt / k))
    gaps.sort()
    segments, cursor = [], y_lo
    for lo, hi in gaps:
        if lo > cursor:
            segments.append((cursor, min(lo, y_hi)))
        cursor = max(cursor, hi)
    if cursor < y_hi:
        segments.append((cursor, y_hi))
    inv = ax.transData.inverted()
    for lo, hi in segments:
        if hi - lo <= 1.0:
            continue
        y0 = inv.transform((x_disp, lo))[1]
        y1 = inv.transform((x_disp, hi))[1]
        line, = ax.plot([x, x], [y0, y1], color=MUTE, lw=LW_REF, zorder=1,
                        solid_capstyle='butt')
        line.set_dashes((2.2, 1.8))
    return segments


def axis_break(ax, x, *, size_pt=4.0):
    """Two hairline slashes on the x spine where the linear part joins the log.

    QA 2026-09-09: the first version converted ``x`` to an axes fraction and
    then drew it through ``get_xaxis_transform`` (which takes DATA x), so on
    the symlog axis both slashes collapsed onto the origin.  The slashes are
    now placed in data x, with their point offsets converted through
    ``transData`` at the spine.
    """
    trans = ax.get_xaxis_transform()
    fig = ax.get_figure()
    k = 72.0 / fig.dpi
    y_ref = ax.transData.transform((x, LOG_YLIM[0]))[1]
    x_disp = ax.transData.transform((x, LOG_YLIM[0]))[0]
    inv = ax.transData.inverted()

    def xd(off_pt):
        return inv.transform((x_disp + off_pt / k, y_ref))[0]

    h = 0.6 * size_pt / axes_h_pt(ax)
    for dx in (-0.30 * size_pt, 0.30 * size_pt):
        ax.plot([xd(dx - 0.35 * size_pt), xd(dx + 0.35 * size_pt)], [-h, h],
                transform=trans, color=COLORS['edge'], lw=LW_HAIR,
                clip_on=False, zorder=6, solid_capstyle='butt')
    return x


