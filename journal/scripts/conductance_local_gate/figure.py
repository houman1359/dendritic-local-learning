# ── private glyph helpers (library geometry, spec 0.2; errata #7) ─────────
def chain(f, xy, parts, *, size=PT_SMALL, color=None, ha='left', va='center',
          zorder=6):
    """Plain strings and (base, sub) pairs laid out left-to-right at ``xy``.

    ``Frame.subscript`` draws every pair (token subscripts, never mathtext)
    and each piece is measured so the run can be centred or right-anchored.
    """
    color = INK if color is None else color
    base_size = PT_ANNOT if size <= PT_SMALL else size
    widths = []
    for p in parts:
        if isinstance(p, tuple):
            widths.append(_text_w_pt(f.ax, p[0], base_size) + 0.4
                          + _text_w_pt(f.ax, p[1], PT_SMALL))
        else:
            widths.append(_text_w_pt(f.ax, p, size))
    total = sum(widths)
    x, y = xy
    if ha == 'center':
        x -= f.fx(total / 2.0)
    elif ha == 'right':
        x -= f.fx(total)
    for p, w in zip(parts, widths):
        if isinstance(p, tuple):
            f.subscript((x, y), p[0], p[1], size=size, color=color, ha='left',
                        va=va, zorder=zorder)
        else:
            f.text((x, y), p, size=size, color=color, ha='left', va=va,
                   zorder=zorder)
        x += f.fx(w)
    return total


