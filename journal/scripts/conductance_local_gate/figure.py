def bound_contact(ax, t):
    """D's bound-contact tick and tag, from all_curves.first_bound_step."""
    cur = t['curves']
    sel = cur[(cur.task == 'opposed_strong') & (cur.rule == 'unit_broadcast')
              & (cur.rate == PRIMARY['rate'])]
    first = sel.groupby('seed').first_bound_step.max()
    contacted = first[first > 0]
    by_4096 = int((contacted <= 4096).sum())
    by_16384 = int((contacted <= 16384).sum())
    assert len(first) == 20 and by_4096 == 18 and by_16384 == 20
    for rule in ('exact', 'hard_distal_unit_proximal',
                 'shunt_proportional_unit_proximal'):
        other = cur[(cur.task == 'opposed_strong') & (cur.rule == rule)
                    & (cur.rate == PRIMARY['rate'])]
        assert int((other.groupby('seed').first_bound_step.max() > 0).sum()) == 0
    median = float(np.median(contacted))
    step = round_half_up(median)
    assert step == 717, step
    band = t['band']
