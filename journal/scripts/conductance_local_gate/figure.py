def display_rows(tables, printed):
    rows = []
    tuning = pd.read_csv(FIG / 'teacher_tuning_source.csv',
                         float_precision='round_trip')
    for _, r in tuning.iterrows():
        rows.append(dict(panel='A', record='nominal teacher',
                         latent_feature=r.z, increasing=r.v_increasing,
                         decreasing=r.v_decreasing))
    band = tables['band']
    for panel, task in (('C', 'aligned_strong'), ('D', 'opposed_strong')):
        sel = band[(band.task == task) & (band.rate == PRIMARY['rate'])
                   & (band.rule.isin(CURVE_RULES))].sort_values(['rule', 'step'])
        for _, r in sel.iterrows():
            rows.append(dict(panel=panel, record='curve band', task=r.task,
                             rule=r.rule, rate=r.rate, step=r.step,
                             mean=r['mean'], ci_low=r.ci_low,
                             ci_high=r.ci_high))
    s = tables['seed_contrasts']
    for budget in (4096, 16384):
        sel = s[(s.task == 'opposed_minus_aligned') & (s.rate == PRIMARY['rate'])
                & (s.budget == budget) & (s.left == 'unit_broadcast')
                & (s.right == 'hard_distal_unit_proximal')].sort_values('seed')
        for _, r in sel.iterrows():
            rows.append(dict(panel='E', record='paired seed difference',
                             task=r.task, budget=r.budget, rate=r.rate,
                             left=r.left, right=r.right, seed=r.seed,
                             difference=r.difference))
        p = printed['E'][str(budget)]
        rows.append(dict(panel='E', record='paired contrast',
                         task='opposed_minus_aligned', budget=budget,
                         rate=PRIMARY['rate'], left='unit_broadcast',
                         right='hard_distal_unit_proximal', n=p['n'],
                         mean=p['mean'], ci_low=p['ci_low'],
                         ci_high=p['ci_high'], positive=p['positive']))
    ep = tables['endpoints']
    f_rules = list(F_ORDER) + ['shunt_proportional_unit_proximal',
                               'unit_broadcast']
    for rate in RATES:
        sel = ep[(ep.task == 'opposed_strong') & (ep.budget == PRIMARY['budget'])
                 & (ep.rate == rate) & (ep.rule.isin(f_rules))
                 ].sort_values(['rule', 'seed'])
        for _, r in sel.iterrows():
            rows.append(dict(panel='F', record='endpoint', task=r.task,
                             budget=r.budget, rate=r.rate, rule=r.rule,
                             seed=r.seed, best_step=r.best_step,
                             test_nmse=r.test_nmse,
                             fixed_endpoint_test_nmse=r.fixed_endpoint_test_nmse,
                             n_changed_parameters=r.n_changed_parameters,
                             g_i0_changed=r.g_i0_changed,
                             g_i1_changed=r.g_i1_changed))
        for rule in f_rules:
            m = cond(tables, 'opposed_strong', rule, rate=rate)
            rows.append(dict(panel='F', record='condition mean',
                             task='opposed_strong', budget=PRIMARY['budget'],
                             rate=rate, rule=rule, n=int(m.n), mean=m['mean'],
                             ci_low=m.ci_low, ci_high=m.ci_high,
                             mean_fixed_endpoint=m.mean_fixed_endpoint))
    h = tables['historical'].sort_values(['evaluated_rule', 'state',
                                          'historical_seed'])
    for _, r in h.iterrows():
        rows.append(dict(panel='G', record='context cancellation',
                         seed=r.historical_seed, state=r.state,
                         rule=r.evaluated_rule,
                         value=r.context_cancellation_ratio))
    return rows


