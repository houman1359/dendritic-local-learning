def y_frac(value):
    lo, hi = LOG_YLIM
    return (math.log10(value) - math.log10(lo)) / (math.log10(hi) - math.log10(lo))


def x_frac(ax, x):
    return ax.transAxes.inverted().transform(ax.transData.transform((x, 1.0)))[0]


def x_data(ax, frac):
    """Axes fraction -> data x (box-independent: the box transforms cancel)."""
    return ax.transData.inverted().transform(ax.transAxes.transform((frac, 0.0)))[0]


def y_data(frac, ylim=None):
    """Axes fraction -> data y on the shared log ladder."""
    lo, hi = LOG_YLIM if ylim is None else ylim
    return 10.0 ** (math.log10(lo) + frac * (math.log10(hi) - math.log10(lo)))


