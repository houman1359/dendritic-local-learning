def min_separation_pt(fig, group_a, group_b):
    """Smallest gap in points between two artist groups (negative = overlap)."""
    renderer = fig.canvas.get_renderer()
    k = 72.0 / fig.dpi
    worst = float('inf')
    for a in group_a:
        ba = a.get_window_extent(renderer)
        for b in group_b:
            bb = b.get_window_extent(renderer)
            gap = max(max(ba.x0 - bb.x1, bb.x0 - ba.x1),
                      max(ba.y0 - bb.y1, bb.y0 - ba.y1))
            worst = min(worst, gap * k)
    return worst


def wrap_lines(ax, text, max_w_pt, max_lines=2):
    """The plan's 'wrap to two lines if it exceeds the axes width' rule.

    Greedy and measured, never abbreviated: ``_wrap_to_width`` delegates to
    ``textwrap`` whose ' [...]' placeholder passes its own word-count guard,
    so a two-line fallback there can silently drop the end of a sentence.
    """
    if _text_w_pt(ax, text, PT_BASE) <= max_w_pt:
        return [text]
    words, lines, cur = text.split(), [], ''
    for word in words:
        trial = word if not cur else f'{cur} {word}'
        if cur and _text_w_pt(ax, trial, PT_BASE) > max_w_pt:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def stack(ax, x_frac, y_frac, lines, *, ha='left', color=None, lead_pt=9.0,
          zorder=6):
    """Stack 7.0-pt lines downward from an axes-fraction anchor."""
    color = MUTE if color is None else color
    arts = []
    for i, line in enumerate(lines):
        if isinstance(line, list):
            a, _ = chain_data(ax, (x_frac, y_frac), line, color=color, ha=ha,
                              va='center', transform=ax.transAxes,
                              zorder=zorder)
            arts += a
        else:
            arts.append(ax.text(x_frac, y_frac, line, transform=ax.transAxes,
                                fontsize=PT_BASE, color=color, ha=ha,
                                va='center', zorder=zorder, clip_on=False))
        y_frac -= lead_pt / axes_h_pt(ax)
    return arts, y_frac


