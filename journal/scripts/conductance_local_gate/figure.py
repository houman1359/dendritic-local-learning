# ── data --------------------------------------------------------------------
def nominal_teacher(opposed):
    """model.teacher's own gains with the log-normal perturbation set to zero."""
    class Silent:
        def normal(self, loc, scale, size):
            return np.zeros(size)
    with mock.patch.object(model.np.random, 'default_rng', lambda *a, **k: Silent()):
        return model.teacher(0, opposed)


def teacher_tuning():
    """Nominal terminal voltage against the latent feature, via model.forward."""
    z = np.linspace(-2.0, 2.0, 201)
    xx = np.tile(np.column_stack([z, z]), (1, 2))
    x = np.column_stack([np.exp(xx), np.exp(-xx), np.zeros((len(z), 2))])
    aligned = model.forward(nominal_teacher(False)[None], x)['voltage'][0]
    opposed = model.forward(nominal_teacher(True)[None], x)['voltage'][0]
    inc, dec = aligned[:, 0], opposed[:, 2]
    assert np.allclose(aligned[:, 2], inc) and np.allclose(opposed[:, 0], inc)
    xp, xm = np.exp(z), np.exp(-z)                       # report.py closed form
    assert np.allclose(inc, (8 * xp + .25 * xm) / (1 + 8 * xp + .25 * xm + .25 * xp + 8 * xm))
    assert np.allclose(dec, (.25 * xp + 8 * xm) / (1 + .25 * xp + 8 * xm + 8 * xp + .25 * xm))
    assert np.all(np.diff(inc) > 0) and np.all(np.diff(dec) < 0)
    table = pd.DataFrame(dict(z=z, v_increasing=inc, v_decreasing=dec))
    table.to_csv(FIG / 'teacher_tuning_source.csv', index=False)
    return table


