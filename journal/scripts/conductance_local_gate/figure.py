def card_tree(f, core, *, head_pt=3.0, foot_pt=14.0):
    """Ghost copy of A's tree with the closed gate at J2 and its own delta-0.

    ``foot_pt`` lifts the soma clear of the card's own bottom edge: the
    library's error_in tail sits (r + 7) pt below the soma, and task_card's
    core reaches the card edge, so a tree drawn on the floor of the core puts
    the delta-0 tag outside the card it belongs to.
    """
    x0, y0, w, h = core
    rect = (x0 + f.fx(12.0), y0 + f.fy(foot_pt), f.fx(34.0),
            h - f.fy(foot_pt + head_pt))
    nodes = f.balanced_tree(rect, depth=2, trunk=False, mode='plain',
                            ghost=True)
    # the double ring alone marks the closed gate: a 'c' badge lands on the
    # exact card's alpha tag at this pitch
    # QA 2026-09-09: no descendant fade on the 34 pt cards (a 38 % hairline
    # subtree vanished at print scale); the closed ring and the open head
    # mark the suppression.
    f.gate(nodes['JR'], closed=True, descendants=None, nodes=nodes,
           node='JR', badge=None)
    sx, sy = nodes.soma
    x1 = sx + f.fx(nodes.soma_r_pt + 1.5)
    f.arrow((x1, sy), (x1 + f.fx(7.0), sy), color=MUTE, lw=LW_EDGE, head=3.4,
            zorder=4.5)
    # side='left': the key column starts 46 pt right of the card edge and the
    # right-hand tag would sit on its first line
    f.error_in(nodes.soma, side='left')
    return nodes


