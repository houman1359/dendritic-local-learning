def _parts_width(ax, parts, size=PT_BASE):
    """Width in points of a chain of str / ('sub'|'sup', s) tokens."""
    total = 0.0
    for p in parts:
        if isinstance(p, tuple):
            total += 0.4 + _text_w_pt(ax, p[1], size)
        else:
            total += _text_w_pt(ax, p, size)
    return total


def chain_data(ax, xy, parts, *, size=PT_BASE, color=None, ha='left',
               va='center', zorder=6, transform=None, drop_pt=1.6,
               rise_pt=2.4):
    """Plain strings and ('sub'|'sup', token) pairs laid out left to right.

    ``Frame.subscript`` (and ``figure_canvas.token_subscript``) draw a
    subscript only, and mathtext is banned by CF-2, so the superscript half of
    ``10`` with a raised exponent is composed here with the same geometry:
    every piece is a real 7.0-pt text span, offset in points from the piece
    before it.  Returns (artists, width_pt).
    """
    color = INK if color is None else color
    transform = ax.transData if transform is None else transform
    width = _parts_width(ax, parts, size)
    x, y = xy
    arts = []
    anchor = ax.text(x, y, '', fontsize=size, ha=ha, va=va,
                     transform=transform, clip_on=False)
    dx = {'left': 0.0, 'center': -width / 2.0, 'right': -width}[ha]
    for p in parts:
        if isinstance(p, tuple):
            kind, s = p
            dy = -drop_pt if kind == 'sub' else rise_pt
            art = ax.annotate(s, xy=(0.0, 0.0), xycoords=anchor,
                              xytext=(dx + 0.4, dy), textcoords='offset points',
                              fontsize=size, color=color, ha='left', va=va,
                              zorder=zorder, annotation_clip=False)
            dx += 0.4 + _text_w_pt(ax, s, size)
        else:
            art = ax.annotate(p, xy=(0.0, 0.0), xycoords=anchor,
                              xytext=(dx, 0.0), textcoords='offset points',
                              fontsize=size, color=color, ha='left', va=va,
                              zorder=zorder, annotation_clip=False)
            dx += _text_w_pt(ax, p, size)
        arts.append(art)
    return arts, width


