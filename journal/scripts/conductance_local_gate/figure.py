    printed['_geometry'] = dict(
        height_pt=HEIGHT_PT, rows_pt=list(ROWS_PT),
        schematic_fraction_b12=round(SCHEMATIC_FRACTION, 4),
        g4_waiver=G4_WAIVER, in_axes_key_exception=KEY_EXCEPTION)
    findings = list(canvas.save(PDF, name='local_gate_primary', dpi=180))
    audit = [str(v) for v in audit_native_pdf(PDF, strict=True)]
    return printed, findings, audit


