def tie_leader(ax, x, y_top_frac, lowest, *, gap_pt=2.2):
    """Hairline from just above a tied annotation to just below its cluster.

    The plan's rule is ``y_text < y_lead < lowest``: the leader starts at the
    text box, not inside it, and stops short of the lowest datum of the
    column it names.
    """
    h = axes_h_pt(ax)
    y0 = y_top_frac + (0.5 * PT_BASE + gap_pt) / h
    y1 = y_frac(float(lowest)) - gap_pt / h
    if y1 - y0 < 1.5 / h:
        return None
    line, = ax.plot([x, x], [y_data(y0), y_data(y1)], color=MUTE,
                    lw=LW_HAIR, zorder=2)
    return line


def mark_points(ax, marks):
    """(category, x, value) marks as (category, x_pt, y_pt) on this axes."""
    w, h = axes_w_pt(ax), axes_h_pt(ax)
    x0, x1 = ax.get_xlim()
    lo, hi = (math.log10(v) for v in LOG_YLIM)
    return [(cat, (x - x0) / (x1 - x0) * w,
             (math.log10(v) - lo) / (hi - lo) * h) for cat, x, v in marks]


def cluster_separation(ax, marks):
    """Closest pair of marks belonging to two DIFFERENT categories, in points.

    This is the quantity the plan's F fallback is written against ('if
    min_separation_pt between adjacent category clusters falls below 1.5 pt,
    drop the two secondary-rate circles ...'): the categories are separated
    along x, so what can collide is a mark of one category with a mark of its
    neighbour, not the value RANGES, which overlap by construction wherever
    two rules succeed equally.
    """
    pts = mark_points(ax, marks)
    worst = float('inf')
    for i, (ca, xa, ya) in enumerate(pts):
        for cb, xb, yb in pts[i + 1:]:
            if abs(ca - cb) != 1:
                continue
            worst = min(worst, math.hypot(xa - xb, ya - yb))
    return float(worst)


