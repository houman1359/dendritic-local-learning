def panel_task(ax, tuning):
    f = Frame(ax)
    core = f.task_card((0.0, 0.0, 1.0, 1.0),
                       footer='24 plastic conductances; context flips each example')
    x0, y0, w, h = core
    core_w, core_h = w * f.w_pt, h * f.h_pt
    iw, ih = 52.0, 34.0                             # inset, lower right (spec A)
    # tree: left of the inset, with a 30-pt band above the canopy for the two
    # staggered rows of stream tags and the subtree tags
    tree = (x0 + f.fx(8.0), y0 + f.fy(12.0), f.fx(96.0), h - f.fy(12.0 + 30.0))
    nodes = f.balanced_tree(tree, depth=2, trunk=False, mode='forward', output='',
                            capsules=list(SUBTREE))
    sx, sy = nodes.soma
    f.subscript((sx + f.fx(nodes.soma_r_pt + 1.5 + 11.0 + 2.5), sy), 'V', 's', ha='left')
    for t in nodes.terminals:                       # inh contact on each terminal branch
        f.contact(_lerp(nodes[nodes.parent[t]], nodes[t], 0.70), kind='inh')
    f.gate(nodes['JL'], closed=False, nodes=nodes, node='JL')
    f.gate(nodes['JR'], closed=True, descendants=['JR'], nodes=nodes, node='JR')
    f.error_in(nodes.soma, side='right')
    gate = COLORS['gate']
    jl, jr = nodes['JL'], nodes['JR']
    f.subscript(f._off(jl, -4.6, -12.0), 'a', 'p', ' = 0', color=gate, ha='right', va='top')
    f.subscript(f._off(jr, 4.6, -12.0), 'a', 'p', ' = 10', color=gate, ha='left', va='top')
    # stream tags: exp(±z1) feeds T1 and T3, exp(±z2) feeds T2 and T4.  Four
    # 32-pt tags over terminals 30 pt apart cannot share one line, so T1/T3
    # sit on the first row above the canopy and T2/T4 on the second; the
    # outer tags are anchored inward so nothing leaves the card.
    top = max(nodes[t][1] for t in nodes.terminals)
    lift = CONTACT_DIA_PT * 0.5 + 3.0
    rows = {'T1': 0, 'T3': 0, 'T2': 1, 'T4': 1}
    anchors = {'T1': ('left', -6.0), 'T2': ('center', 0.0), 'T3': ('center', 0.0),
               'T4': ('right', 6.0)}
    for t, sub in zip(nodes.terminals, ('1', '2', '1', '2')):
        ha, dx = anchors[t]
        f.subscript((nodes[t][0] + f.fx(dx), top + f.fy(lift + 9.0 * rows[t])),
                    'exp(±z', sub, ')', size=PT_SMALL, ha=ha, va='bottom')
    for (root, cname), tag in zip(SUBTREE, ('subtree 1', 'subtree 2')):
        terms = nodes.terminals_under(root)
        cx = np.mean([nodes[t][0] for t in terms])
        f.text((cx, top + f.fy(lift + 19.0)), tag, size=PT_SMALL,
               color=label_color(COLORS[cname]), va='bottom')
    # inset: nominal teacher terminal voltage against the latent feature
    rect = (x0 + w - f.fx(iw + 3.0), y0 + f.fy(20.0), f.fx(iw), f.fy(ih))
    inner = f.axes_inset(rect)
    inner.plot(tuning.z, tuning.v_increasing, color=INK, lw=LW_REF, zorder=3)
    dec, = inner.plot(tuning.z, tuning.v_decreasing, color=INK, lw=LW_REF, zorder=3)
    dec.set_dashes((2.2, 1.8))
    z_end = 1.82
    for col, cname in (('v_increasing', 'dend'), ('v_decreasing', 'soma')):
        y = float(np.interp(z_end, tuning.z, tuning[col]))
        inner.plot([z_end], [y], marker='s', ms=6.0, mfc=COLORS[cname], mec='none',
                   ls='none', clip_on=False, zorder=4)
    inner.set_xlim(-2.0, 2.0)
    inner.set_ylim(0.0, 1.0)
    inner.set_xticks([-2, 2], ['−2', '2'])
    inner.set_yticks([0, 1], ['0', '1'])
    inner.tick_params(labelsize=PT_TICK, pad=1.5)
    inner.text(0.0, 0.06, 'z', fontsize=PT_TICK, color=INK, ha='center', va='bottom')
    f.text((x0 + w - f.fx(3.0), rect[1] + f.fy(ih + 4.0)), 'opposed flips\nsubtree 2',
           size=PT_SMALL, ha='right', va='bottom', linespacing=1.15)
    return nodes


# ── B: the four deliveries ────────────────────────────────────────────────
def card_tree(f, cell):
    """Ghost copy of A's tree with the closed gate at J2 and δ0 (spec B)."""
    x0, y0, w, h = cell
    rect = (x0 + f.fx(2.0), y0 + f.fy(9.5), f.fx(50.0), h - f.fy(9.5 + 4.0))
    nodes = f.balanced_tree(rect, depth=2, trunk=False, mode='plain', ghost=True)
    # the double ring alone marks the closed gate: a 'c' badge lands on the
    # exact card's alpha tag at this 11-pt pitch (text is dropped, never shrunk)
    f.gate(nodes['JR'], closed=True, descendants=['JR'], nodes=nodes, node='JR', badge=None)
    sx, sy = nodes.soma
    x1 = sx + f.fx(nodes.soma_r_pt + 1.5)
    f.arrow((x1, sy), (x1 + f.fx(11.0), sy), color=MUTE, lw=LW_EDGE, head=3.4, zorder=4.5)
    f.error_in(nodes.soma, side='right')
    return nodes


