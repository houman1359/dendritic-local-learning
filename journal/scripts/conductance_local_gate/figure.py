# ── E: gate placement ─────────────────────────────────────────────────────
E_ORDER = ('exact', 'hard_distal_unit_proximal', 'swapped_distal_unit_proximal', 'hard_distal_and_proximal')
E_LABELS = ('Exact\npath', 'Distal\ngate', 'Swapped\ngate', 'Also\nproximal')
# 'Gate also / proximal' (32 pt) beside 'Swapped' (31 pt) cannot share a
# 28-pt category pitch at PT_SMALL; the fourth category reads 'Also proximal'.


def placement(ax, t):
    ep = t['endpoints']
    printed = {}
    for i, rule in enumerate(E_ORDER):
        f = ep[(ep.task == 'opposed_strong') & (ep.rate == PRIMARY['rate']) & (ep.budget == PRIMARY['budget']) & (ep.rule == rule)].sort_values('seed')
        m = cond(t, 'opposed_strong', rule)
        seeds_and_mean(ax, i, f.test_nmse, m['mean'], m.ci_low, m.ci_high, rc(rule))
        printed[rule] = dict(mean=float(m['mean']), ci_low=float(m.ci_low), ci_high=float(m.ci_high),
                             g_i0_changed=int(f.g_i0_changed.sum()), g_i1_changed=int(f.g_i1_changed.sum()),
                             both_frozen=int((~f.g_i0_changed & ~f.g_i1_changed).sum()), n=int(len(f)))
    frozen = printed['hard_distal_and_proximal']['both_frozen']
    assert frozen == 20 and printed['swapped_distal_unit_proximal']['g_i0_changed'] == 16
    bc = cond(t, 'opposed_strong', 'unit_broadcast')['mean']
    ax.set_xlim(-.3, 3.45)                   # >= 31-pt category pitch, no overhang
    plain_log_ticks(ax)
    ax.set_ylim(*LOG_YLIM)
    reference_line(ax, bc, label=None)
    ax.annotate(f'broadcast {bc:.2f}', xy=(-.3, bc), xytext=(1.4, 1.4), textcoords='offset points',
                fontsize=PT_SMALL, color=MUTE, ha='left', va='bottom', zorder=5)
    ax.set_xticks(range(4), E_LABELS)
    ax.tick_params(axis='x', labelsize=PT_SMALL, pad=2.0)
    ax.set_ylabel('Opposed NMSE')
    style_panel(ax)
    token_subscript(ax, 1.2, 2.2e-3, 'g', 'I', f' frozen {frozen}/20', size=PT_ANNOT, ha='left')
    ax.plot([3.0, 3.0], [3.3e-3, 5.5e-3], color=MUTE, lw=LW_HAIR, zorder=2)
    return printed


# ── F: the primary estimand ───────────────────────────────────────────────
def interaction(ax, t):
    c, s = t['contrasts'], t['seed_contrasts']
    color = COLORS['shunting']
    printed = {}
    for i, budget in enumerate((4096, 16384)):
        sel = (s.task == 'opposed_minus_aligned') & (s.rate == PRIMARY['rate']) & (s.budget == budget) & (s.left == 'unit_broadcast') & (s.right == 'hard_distal_unit_proximal')
        vals = s[sel].sort_values('seed').difference
        m = c[(c.task == 'opposed_minus_aligned') & (c.rate == PRIMARY['rate']) & (c.budget == budget) & (c.left == 'unit_broadcast') & (c.right == 'hard_distal_unit_proximal')].iloc[0]
        assert len(vals) == 20 and abs(vals.mean() - m['mean']) < 1e-12 and int(m.positive) == int((vals > 0).sum())
        seeds_and_mean(ax, i, vals, m['mean'], m.ci_low, m.ci_high, color)
        printed[str(budget)] = dict(mean=float(m['mean']), ci_low=float(m.ci_low), ci_high=float(m.ci_high), positive=int(m.positive))
    ax.set_xlim(-.5, 1.5)
    ax.set_ylim(*UNIT_YLIM)
    ax.set_yticks([0, .5, 1], ['0', '0.5', '1'])
    ax.set_xticks([0, 1], ['4,096', '16,384'])
    reference_line(ax, 0.0, label=None)
    ax.annotate('no interaction', xy=(1.5, 0.0), xytext=(0.0, -1.4), textcoords='offset points',
                fontsize=PT_SMALL, color=MUTE, ha='right', va='top', zorder=5)
    ax.set_xlabel('Window (updates)')
    # one-line y label (a second line pushes the F letter onto E's axes
    # corner); the opposed − aligned qualifier is the in-panel note
    ax.set_ylabel('Broadcast − gate NMSE')
    style_panel(ax)
    pos = ', '.join(f'{printed[str(b)]["positive"]}/20' for b in (4096, 16384))
    ax.text(0.5, 1.42, f'opposed − aligned;\npositive in {pos} seeds', ha='center', va='top',
            fontsize=PT_SMALL, color=MUTE, linespacing=1.15)
    return printed


# ── G: context-gradient cancellation (earlier cohort) ─────────────────────
def cancellation(ax, t):
    h = t['historical']
    assert len(h) == 80 and set(h.historical_seed) == set(range(2101, 2121))
    rng = np.random.default_rng(HIST_SEED)
    printed = {}
    for rule, offset, marker, color in (('exact', -.12, 'o', COLORS['bp']),
                                        ('calibrated_broadcast', .12, 's', COLORS['per_soma'])):
        means = []
        for i, state in enumerate(('initial', 'extended_best')):
            part = h[(h.state == state) & (h.evaluated_rule == rule) & (h.source_rule == 'calibrated_broadcast')].sort_values('historical_seed')
            assert len(part) == 20
            vals = part.context_cancellation_ratio.to_numpy()
            lo, hi = boot(vals, rng)
            seeds_and_mean(ax, i + offset, vals, vals.mean(), lo, hi, color, marker=marker)
            means.append(vals.mean())
            printed[f'{rule}_{state}'] = dict(mean=float(vals.mean()), ci_low=float(lo), ci_high=float(hi))
        ax.plot([offset, 1 + offset], means, color=color, lw=LW_HAIR, zorder=3)
    assert abs(printed['exact_initial']['mean'] - 0.636) < 2e-3 and abs(printed['calibrated_broadcast_extended_best']['mean'] - 0.172) < 2e-3
    ax.set_xlim(-.5, 1.5)
    ax.set_ylim(*UNIT_YLIM)
    ax.set_yticks([0, .5, 1], ['0', '0.5', '1'])
    ax.set_xticks([0, 1], ['Initial', 'Broadcast-\ntrained'])
    ax.tick_params(axis='x', labelsize=PT_SMALL, pad=2.0)
    reference_line(ax, 1.0, label='no cancellation')
    ax.set_ylabel('Gradient retained')
    style_panel(ax)
    ax.text(0.40, 0.55, 'exact', ha='center', va='center', fontsize=PT_LEGEND, color=COLORS['bp'])
    # the only band free of seeds is under the two clusters, so the label
    # runs along the axis floor beside the calibrated squares
    ax.text(0.85, -0.13, 'calibrated broadcast', ha='center', va='center', fontsize=PT_LEGEND,
            color=label_color(COLORS['per_soma']))
    ax.text(-.42, 1.42, 'earlier cohort, seeds 2101–2120;\ncalibrated broadcast', ha='left', va='top',
            fontsize=PT_SMALL, color=MUTE, linespacing=1.15)
    return printed


# ── assembly ──────────────────────────────────────────────────────────────
def build(cfg, tables, tuning):
    canvas = NativeCanvas(HEIGHT_PT / 72, 3, row_weights=ROWS_PT, hgutter_pt=HGUTTER_PT,
                          vgutter_pt=VGUTTER_PT, margins=Margins(**MARGINS))
    a = canvas.panel('A', 0, 0, 5, schematic=True, lock=False, title='Context shunts one branch')
    b = canvas.panel('B', 0, 5, 7, schematic=True, lock=False, title='Four ways to deliver the somatic error')
    c = canvas.panel('C', 1, 0, 6, title='Aligned: all rules learn')
    d = canvas.panel('D', 1, 6, 6, title='Opposed: broadcast fails')
    e = canvas.panel('E', 2, 0, 4, title='Gate placement decides')
    f_ = canvas.panel('F', 2, 4, 4, title='Task-specific gate benefit')
    g = canvas.panel('G', 2, 8, 4, title='Context gradients cancel')
    panel_task(a, tuning)
    panel_deliveries(b)
    curves(c, tables, 'aligned_strong', legend=True)
    curves(d, tables, 'opposed_strong', shared=True)
    printed = dict(D=curve_labels(d, tables), E=placement(e, tables), F=interaction(f_, tables),
                   G=cancellation(g, tables))
    # oracle badge after C's legend entry text, anchored in points to the axes corner
    canvas.fig.canvas.draw()
    r = canvas.fig.canvas.get_renderer()
    box = c._oracle_entry.get_window_extent(r)
    corner = c.transAxes.transform((0.0, 0.0))
    k = 72.0 / canvas.fig.dpi
    badge_at(c, (0.0, 0.0), 'oracle', xycoords='axes fraction',
             offset_pt=((box.x1 - corner[0]) * k + 3.0, ((box.y0 + box.y1) / 2 - corner[1]) * k),
             ha='left', va='center')
    # One axes width per span family (strict audit 'row-alignment'): reserves
    # are locked per grid column, so a right-side need of G (column 12) would
    # narrow D but not C.  Declare the widest left / right need of any data
    # panel for all of them, so C = D and E = F = G exactly.
    canvas.lock_reserves()
    data_panels = ('C', 'D', 'E', 'F', 'G')
    left = max(canvas._locks[n][0] for n in data_panels)
    right = max(canvas._locks[n][1] for n in data_panels)
    # A mid-row letter sits 36 pt left of its panel's y-label stack, i.e. on
    # the 38-pt gutter's far edge: a 4-pt right reserve keeps the F and G
    # letters clear of E's and F's title boxes (align_letters).
    right = max(right, 4.0)
    # row 2 letters must sit >= 8.5 pt below row 1's x labels (audit_row_separation)
    row2_top = max(canvas._locks[n][2] for n in ('E', 'F', 'G')) + 5.0
    for n in data_panels:
        canvas.declare_reserve(n, left=left, right=right,
                               top=row2_top if n in ('E', 'F', 'G') else canvas._locks[n][2],
                               bottom=canvas._locks[n][3])
    canvas.lock_reserves()
    findings = list(canvas.align_letters())
    problems = findings + list(canvas.save(PDF, name='local_gate_primary', dpi=180))
    audit = [str(v) for v in audit_native_pdf(PDF, strict=True)]
    return printed, problems, audit


