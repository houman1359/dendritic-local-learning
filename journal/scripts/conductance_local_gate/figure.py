def curves(ax, t, task, *, legend=False, shared=False):
    band = t['band']
    ends = {}
    for rule in CURVE_RULES:
        b = band[(band.task == task) & (band.rule == rule) & (band.rate == PRIMARY['rate'])].sort_values('step')
        color = rc(rule)
        ax.fill_between(b.step, b.ci_low, b.ci_high, color=color, alpha=.14, lw=0, zorder=1)
        ax.plot(b.step, b['mean'], color=color, lw=LW_DATA, zorder=3, label=RULES[rule][0])
        ends[rule] = b
    ax.set_xscale('symlog', linthresh=64)
    ax.set_xlim(0, 16384)
    # a '4,096' tick 35 pt from '16,384' collides at PT_TICK, so the primary
    # window is named on its dashed reference instead
    ax.set_xticks([0, 64, 1024, 16384], ['0', '64', '1,024', '16,384'])
    ax.xaxis.set_minor_locator(NullLocator())
    plain_log_ticks(ax)
    ax.set_ylim(*LOG_YLIM)
    ax.set_xlabel('Updates')
